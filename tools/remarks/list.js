#!/usr/bin/env node
// Writes docs/remarks/REMARKS.md from the bank (src/lib/remarks/bank/*.js):
// every line, grouped by situation, with its id, and the counts on top. The
// bank is the only copy — run this after changing it.
"use strict";

const fs = require("fs");
const path = require("path");
const { KINDS } = require("../../src/lib/remarks/bank");

const WHEN = {
  "everyday-morning": "Home, 5:00–11:59, nothing special known", "everyday-afternoon": "Home, 12:00–16:59",
  "everyday-evening": "Home, 17:00–22:59", "everyday-night": "Home, 23:00–4:59", "everyday-any": "Home, any time",
  "now-3am": "Home, 2:00–4:59 right now", "workday-morning": "a workday, 6–10", "work-hours": "a workday, 10–12 and 14–17",
  lunch: "a workday, 12–14", "friday-night": "Friday from 17:00", saturday: "Saturday 11–18",
  "weekend-ending": "the last weekend day from 17:00 (Saturday in Israel, Sunday elsewhere)",
  "week-start": "the first workday ({day} = its name)", midweek: "the middle workday, evening",
  "weekend-morning": "a weekend day, 7–12", "new-year": "1 January", valentines: "14 February",
  halloween: "31 October", christmas: "24–25 December", "new-years-eve": "31 December",
  "friday-13": "a Friday the 13th", "april-first": "1 April",
  "away-week": "last watched 7–27 days ago", "away-month": "last watched 28+ days ago",
  "late-last-night": "watched between midnight and 5 last night, now after 7",
  "heavy-yesterday": "4+ hours yesterday ({n})", "heavy-today": "3+ hours today already ({n})",
  streak: "5+ days in a row ({n})", "left-show": "a show left mid-way 2 weeks to 4 months ago, still active",
  "finished-series": "the last episode of a show, in the last 4 days", "one-show": "one show is 60%+ of the last 3 weeks",
  rewatch: "a title come back to, 3+ times, lately ({n} = times)", "mylist-grows": "20+ titles in My List ({n})",
  "genre-diet": "55%+ of 60 days in one genre", "phone-mostly": "70%+ of the last month's plays on a phone",
  "browsing-nothing": "3+ fresh visits today, nothing played", "harsh-ratings": "6+ ratings averaging 2.3 or less",
  "generous-ratings": "8+ ratings averaging 4.6 or more", "downloads-unwatched": "3+ of their downloads, landed 2–45 days ago, never played",
  "new-episode": "a show they follow has an episode out they have not seen", "night-owl": "40%+ of the last month's plays start after midnight",
  sampler: "60%+ of 3 weeks' plays stop before 10 minutes", "just-back": "a 20+ minute play ended under 30 minutes ago",
  "first-visit": "no history at all",
};

const groups = {};
for (const def of Object.values(KINDS)) (groups[def.group] = groups[def.group] || []).push(def);
const TITLES = { everyday: "Home — everyday", calendar: "Home — the clock and the calendar", habits: "Home — their own viewing",
  kids: "Home — kids profiles", roasts: "Wrapped — roast cards", places: "Other screens (written, not wired yet)" };

const count = (d) => d.lines.filter(Boolean).length;
const total = Object.values(KINDS).reduce((s, d) => s + count(d), 0);
const out = ["# Aurora's remarks — every line", "",
  `Generated by \`node tools/remarks/list.js\` from src/lib/remarks/bank — edit the bank, not this file. The voice: [VOICE.md](VOICE.md). A line's id is what to quote to veto it ("cut em-12").`, "",
  `**${total} lines** in ${Object.keys(KINDS).length} situations.`, ""];
for (const [g, defs] of Object.entries(groups)) {
  out.push(`- ${TITLES[g] || g}: ${defs.reduce((s, d) => s + count(d), 0)} — ` + defs.map((d) => `${d.kind} ${count(d)}`).join(", "));
}
for (const [g, defs] of Object.entries(groups)) {
  out.push("", `## ${TITLES[g] || g}`);
  for (const d of defs) {
    out.push("", `### ${d.kind} (${count(d)})${WHEN[d.kind] ? ` — ${WHEN[d.kind]}` : ""}`, "");
    for (const l of d.lines) if (l) out.push(`- \`${l.id}\` ${l.text}`);
  }
}
const file = path.join(__dirname, "../../docs/remarks/REMARKS.md");
fs.writeFileSync(file, out.join("\n") + "\n");
console.log(`wrote ${path.relative(process.cwd(), file)}: ${total} lines`);
