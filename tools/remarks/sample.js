#!/usr/bin/env node
// A made-up person's fortnight of Home visits, to read the remarks the way a
// person meets them: `node tools/remarks/sample.js` prints 40 picks (Markdown;
// docs/remarks/SAMPLE.md is its output). Pure — the picker, the situations and
// a seeded random; nothing is read from or written to a server.
"use strict";

const { pick, newMemory } = require("../../src/lib/remarks/picker");
const { clockOf, situationsFor } = require("../../src/lib/remarks/situations");

let seed = Number(process.argv[2]) || 20261110;
const rng = () => { seed = (seed * 1103515245 + 12345) % 2147483648; return seed / 2147483648; };

const TZO = -120; // Israel in winter
const TZ = "Asia/Jerusalem";
const start = Date.parse("2026-11-08T00:00:00+02:00"); // a Sunday
const H = 3600000, DAY = 24 * H;

// [day, hour, facts] — the story: back after a month, then hooked again.
const visits = [
  [0, 8, { awayMs: 35 * DAY }], [0, 13, { awayMs: 35 * DAY }], [0, 21, { awayMs: 35 * DAY }],
  [1, 7, { lateLastNight: true, leftShow: "Slow Horses" }], [1, 12, { leftShow: "Slow Horses" }],
  [1, 22, { leftShow: "Slow Horses", justBack: true }],
  [2, 9, { yesterdayHours: 4, myList: 34 }], [2, 18, { myList: 34, genre: "thrillers" }],
  [2, 23, { todayHours: 3, myList: 34 }],
  [3, 3, { genre: "thrillers", nightOwl: true }], [3, 10, { lateLastNight: true, streak: 5 }],
  [3, 19, { streak: 5, newEpisode: "The Bear" }],
  [4, 8, { streak: 6, newEpisode: "The Bear" }], [4, 17, { streak: 6, oneShow: "The Bear" }],
  [4, 21, { streak: 6, ratings: "harsh" }],
  [5, 11, { streak: 7, myList: 35 }], [5, 18, { streak: 7, unwatchedDownloads: 4 }],
  [5, 22, { streak: 7, todayHours: 4 }],
  [6, 9, { yesterdayHours: 5, streak: 8 }], [6, 14, { streak: 8, rewatch: { title: "Paddington 2", n: 3 } }],
  [6, 20, { streak: 8 }],
  [7, 7, { streak: 9, phoneMostly: true }], [7, 13, {}], [7, 20, { finishedSeries: "The Bear" }],
  [8, 2, { nightOwl: true }], [8, 12, { lateLastNight: true }], [8, 19, { browsingToday: 3 }],
  [9, 10, { sampler: true }], [9, 18, { sampler: true, genre: "thrillers" }],
  [10, 8, {}], [10, 12, { myList: 36 }], [10, 21, { justBack: true }],
  [11, 9, { leftShow: "Severance" }], [11, 17, { newEpisode: "Slow Horses" }], [11, 22, {}],
  [12, 7, {}], [12, 13, { ratings: "harsh" }], [12, 19, { unwatchedDownloads: 5 }],
  [13, 11, { streak: 3 }], [13, 20, { myList: 37 }],
];

const memory = newMemory();
const out = ["# A fortnight of remarks (sample)", "",
  "A made-up person (zone Asia/Jerusalem) back after a month away, then hooked again. 40 Home visits; each line is what Home would say. Generated by `node tools/remarks/sample.js` — the picker, the situations and a seeded random, nothing else.", "",
  "| # | when | what applies (besides the clock) | id | the remark |", "|---|---|---|---|---|"];
visits.forEach(([d, h, facts], i) => {
  const now = start + d * DAY + h * H;
  const clock = clockOf(now, TZO, TZ);
  const r = pick(situationsFor(facts, clock), memory, { now, rng });
  const when = new Date(now - TZO * 60000).toISOString().replace("T", " ").slice(0, 16) + ` (${["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"][clock.weekday]})`;
  const what = Object.entries(facts).map(([k, v]) => (v === true ? k : `${k}=${typeof v === "object" ? v.title : v}`)).join(", ") || "—";
  out.push(`| ${i + 1} | ${when} | ${what} | ${r.id} (${r.kind}) | ${r.text} |`);
});
console.log(out.join("\n"));
